"""Parametrized Nginx configuration generator."""
import json
import re
from pathlib import Path
from urllib.parse import quote
CONFIG_FILE=Path('/etc/stremioproxywan/config.json')
DEFAULTS={
 'wan_host':'str.example.com','wan_port':443,'wan_tls_mode':'selfsigned',
 'wan_address_mode':'ddns',
 'wan_cert':'/etc/stremioproxywan/tls/fullchain.pem',
 'wan_key':'/etc/stremioproxywan/tls/privkey.pem',
 'lan_host':'lan.example.invalid','lan_http_port':8080,'lan_core_port':11470,
 'backend_scheme':'https','backend_host':'backend.example.invalid',
 'backend_port':12470,'backend_tls_name':'backend.example.invalid',
 'backend_ca':'/etc/ssl/certs/ca-certificates.crt','http_policy':'disabled'
}
HOST_RE=re.compile(r'^[a-zA-Z0-9][a-zA-Z0-9.\-]{0,252}$')
def validate(raw):
 d={**DEFAULTS,**raw}
 for k in ('wan_host','lan_host','backend_host','backend_tls_name'):
  v=d[k]
  if not isinstance(v,str) or not HOST_RE.fullmatch(v) or '..' in v: raise ValueError('Invalid host: '+str(v))
  d[k]=v.lower()
 for k in ('wan_port','lan_http_port','lan_core_port','backend_port'):
  d[k]=int(d[k])
  if not 1<=d[k]<=65535: raise ValueError('Invalid port: '+k)
 for k in ('wan_cert','wan_key','backend_ca'):
  v=Path(d[k])
  if not v.is_absolute() or '"' in str(v) or '\n' in str(v) or '\r' in str(v): raise ValueError('Invalid path: '+k)
  d[k]=str(v)
 if d['wan_tls_mode'] not in ('trusted','selfsigned'): raise ValueError('Invalid WAN TLS mode')
 if d['wan_address_mode'] not in ('ddns','static','direct_ip'): raise ValueError('Invalid WAN address mode')
 if d['wan_address_mode']=='direct_ip':
  import ipaddress
  try: ipaddress.IPv4Address(d['wan_host'])
  except ipaddress.AddressValueError as exc: raise ValueError('direct_ip requires WAN IPv4') from exc
 if d['backend_scheme'] not in ('http','https'): raise ValueError('Invalid backend scheme')
 if d['http_policy'] not in ('disabled','redirect','legacy_proxy'): raise ValueError('Invalid HTTP policy')
 return d
def require_deployment_values(d):
    if d['wan_host'].endswith('.example.com') or d['wan_host'].endswith('.invalid'):
        raise ValueError('Configure an actual WAN hostname or IP')
    if d['lan_host'].endswith('.invalid') or d['backend_host'].endswith('.invalid'):
        raise ValueError('Configure the LAN and backend addresses')
    if d['backend_scheme']=='https' and d['backend_tls_name'].endswith('.invalid'):
        raise ValueError('Configure the backend TLS hostname')

def nginx_config(raw):
 d=validate(raw)
 w,lan,b=d['wan_host'],d['lan_host'],d['backend_host']
 source=re.escape(quote('https://'+w+(':'+str(d['wan_port']) if d['wan_port']!=443 else ''),safe=''))
 target=quote(f'http://{lan}:{d["lan_core_port"]}',safe='')
 http=''
 if d['http_policy']=='redirect':
  http=f"server {{ listen 80; server_name {w}; return 301 https://{w}:{d['wan_port']}$request_uri; }}\n"
 elif d['http_policy']=='legacy_proxy':
  http=f"""server {{ listen 80; server_name {w};
 location / {{ proxy_pass http://{lan}:{d['lan_http_port']}; proxy_set_header Host $host; proxy_buffering off; }}
}}\n"""
 tls=''
 if d['backend_scheme']=='https':
  tls=f"""        proxy_ssl_server_name on;
        proxy_ssl_name {d['backend_tls_name']};
        proxy_ssl_verify on;
        proxy_ssl_trusted_certificate {d['backend_ca']};
        proxy_ssl_verify_depth 3;
"""
 return f"""# GENERATED by stremioproxywan; do not edit directly
map $http_upgrade $connection_upgrade {{ default upgrade; '' close; }}
map $http_authorization $stremio_backend_authorization {{ default $http_authorization; ~*^Basic ""; }}
map "$uri|$args" $stremio_hls_media_args {{
 default "";
 ~*^/hlsv2/[^|]*\\|(?<hls_pre>.*mediaURL=){source}(?<hls_post>%2F.*)$ "${{hls_pre}}{target}${{hls_post}}";
}}
{http}server {{
 listen {d['wan_port']} ssl http2;
 server_name {w};
 ssl_certificate {d['wan_cert']};
 ssl_certificate_key {d['wan_key']};
 ssl_protocols TLSv1.2 TLSv1.3;
 location = /_session/start {{
  auth_basic "Stremio - acesso restrito";
  auth_basic_user_file /etc/stremioproxywan/users.htpasswd;
  proxy_pass http://127.0.0.1:18765/issue;
  proxy_set_header X-Authenticated-User $remote_user;
 }}
 location = /_session/check {{
  internal;
  proxy_pass http://127.0.0.1:18765/check;
  proxy_pass_request_body off;
  proxy_set_header Content-Length "";
  proxy_set_header Cookie $http_cookie;
 }}
 location / {{
  satisfy any;
  auth_basic "Stremio - acesso restrito";
  auth_basic_user_file /etc/stremioproxywan/users.htpasswd;
  auth_request /_session/check;
  if ($stremio_hls_media_args) {{ set $args $stremio_hls_media_args; }}
  proxy_pass {d['backend_scheme']}://{b}:{d['backend_port']};
{tls}  proxy_http_version 1.1;
  proxy_set_header Host {d['backend_tls_name'] if d['backend_scheme']=='https' else b};
  proxy_set_header X-Forwarded-Host $host;
  proxy_set_header X-Real-IP $remote_addr;
  proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
  proxy_set_header X-Forwarded-Proto https;
  proxy_set_header Authorization $stremio_backend_authorization;
  proxy_set_header Range $http_range;
  proxy_set_header If-Range $http_if_range;
  proxy_set_header Upgrade $http_upgrade;
  proxy_set_header Connection $connection_upgrade;
  proxy_buffering off;
  proxy_connect_timeout 20s;
  proxy_read_timeout 3600s;
  proxy_send_timeout 3600s;
 }}
}}
"""
